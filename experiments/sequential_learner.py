    current_in_tokens, current_out_tokens = [], []

    import datetime
    run_session_id = f"benchmark-{datetime.datetime.now().strftime('%Y%m%d-%H%M')}"
    if _lf_enabled:
        print(f"  Langfuse session: {run_session_id}")

    for i, question in enumerate(QUERIES, 1):
        print(f"\n[{i}/{len(QUERIES)}] {question}")

        trace_ctx = (
            _lf.start_as_current_observation(name=f"Q{i}: {question[:60]}", as_type="trace",
                                              session_id=run_session_id,
                                              metadata={"query_index": i, "prompt_version": len(prompt_versions) - 1})
            if _lf_enabled else None
        )
        trace_id = None
        if trace_ctx:
            trace_ctx.__enter__()
            try:
                trace_id = _lf.get_current_trace_id()
            except Exception:
                pass

        # Step 1: Haiku answers
        answer = None
        judgment = {}
        gen_time, inp, out = 0, 0, 0
        print(f"  Haiku answering...", end="", flush=True)
        try:
            answer, gen_time, inp, out = answer_query(client, question, summary, current_prompt)
            current_in_tokens.append(inp)
            current_out_tokens.append(out)
            print(f" {gen_time}s ({inp}in/{out}out tokens)", end="", flush=True)
            if _lf_enabled:
                try:
                    with _lf.start_as_current_observation(
                        name="haiku-generation", as_type="generation",
                        input=question, output=answer, model=GENERATOR_MODEL,
                        metadata={"latency_s": gen_time, "input_tokens": inp, "output_tokens": out},
                    ):
                        pass
                except Exception:
                    pass
        except Exception as e:
            print(f" ERROR: {e}")
            if trace_ctx:
                try: trace_ctx.__exit__(None, None, None)
                except Exception: pass
            results.append({
                "question": question, "answer": "ERROR", "judgment": {},
                "gen_time": 0, "input_tokens": 0, "output_tokens": 0,
                "prompt_version": len(prompt_versions) - 1, "fix_applied": None, "fix_time": 0,
            })
            continue

        # Step 2: Opus judges
        print(f" | Opus judging...", end="", flush=True)
        try:
            judgment = judge_answer(client, question, answer, summary)
            verdict = judgment.get("verdict", "?")
            score = judgment.get("overall", "?")
            print(f" {judgment.get('_judge_time')}s | {verdict} ({score}/10)")
            if _lf_enabled:
                try:
                    with _lf.start_as_current_observation(
                        name="opus-judgment", as_type="generation",
                        input=question, output=json.dumps(judgment), model=JUDGE_MODEL,
                        metadata={"latency_s": judgment.get("_judge_time", 0)},
                    ):
                        pass
                    if trace_id:
                        for metric in ("overall", "factual_accuracy", "completeness", "clarity"):
                            val = judgment.get(metric)
                            if isinstance(val, (int, float)):
                                _lf.create_score(trace_id=trace_id, name=metric, value=val / 10)
                        _lf.create_score(trace_id=trace_id, name="pass",
                                         value=1.0 if verdict == "PASS" else 0.0)
                except Exception:
                    pass
        except Exception as e:
            print(f" ERROR: {e}")
            judgment = {"error": str(e)}

        if trace_ctx:
            try: trace_ctx.__exit__(None, None, None)
            except Exception: pass

        # Step 3: Apply fix to prompt (unless last query)
        fix_applied = None
        fix_time = 0
        if i < len(QUERIES) and "prompt_fix" in judgment and judgment["prompt_fix"]:
            fix_instruction = judgment["prompt_fix"]
            print(f"  Applying fix: \"{fix_instruction[:80]}...\"" if len(fix_instruction) > 80 else f"  Applying fix: \"{fix_instruction}\"")
            print(f"  Updating prompt (Opus)...", end="", flush=True)
            try:
                current_prompt, fix_time = apply_fix(client, current_prompt, fix_instruction)
                print(f" {fix_time}s")
                fix_applied = fix_instruction
                prompt_versions.append({
                    "after_q": i,
                    "prompt": current_prompt,
                    "label": f"AFTER Q{i}: {fix_instruction[:100]}",
                })
            except Exception as e:
                print(f" ERROR (keeping previous prompt): {e}")

        results.append({
            "question": question,
            "answer": answer,
            "judgment": judgment,
            "gen_time": gen_time,
            "input_tokens": inp,
            "output_tokens": out,
            "prompt_version": len(prompt_versions) - 1,
            "fix_applied": fix_applied,
            "fix_time": fix_time,
        })

        time.sleep(1)

    _lf_flush()

    # Aggregate current-run stats
    cur_scores = [r["judgment"].get("overall", 0) for r in results if "overall" in r["judgment"]]
    cur_pass = sum(1 for r in results if r["judgment"].get("verdict") == "PASS")
    cur_avg_score = round(sum(cur_scores) / max(len(cur_scores), 1), 2)
